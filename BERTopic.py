def name_topic(keywords):
    all_words = set()
    for kw in keywords:
        for w in kw.lower().split():
            all_words.add(w)
        all_words.add(kw.lower())
    for trigger_set, label in TOPIC_NAME_MAP:
        if all_words & trigger_set:
            return label
    clean = [k for k in keywords[:3] if len(k) > 3]
    return " / ".join(k.title() for k in clean) if clean else "Uncategorized"

