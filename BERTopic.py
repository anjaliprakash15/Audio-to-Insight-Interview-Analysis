LINE_RE = re.compile(
    r"^\[(\d+(?:\.\d+)?)[–\-](\d+(?:\.\d+)?)\]\s*(speaker_\d+)\s*:\s*(.*)$",
    flags=re.IGNORECASE,
)

def parse_transcript(text):
    rows = []
    for line in text.splitlines():
        line = line.strip()
        if not line:
            continue
        m = LINE_RE.match(line)
        if m:
            content = m.group(4).strip()
            if content:
                rows.append({
                    "start":    float(m.group(1)),
                    "end":      float(m.group(2)),
                    "speaker":  m.group(3).lower(),
                    "content":  content,
                    "raw_line": line,
                })
    return rows

def looks_like_question(text):
    t = text.strip().lower()
    if "?" in t:
        return True
    starters = (
        "what", "why", "how", "when", "where", "who", "which",
        "do you", "did you", "are you", "have you", "can you",
        "could you", "would you", "should you", "will you",
        "tell me", "describe", "explain",
    )
    return any(t.startswith(s) for s in starters)

def detect_participant_speaker(rows):
    if not rows:
        return None
    by_spk = defaultdict(list)
    for row in rows:
        by_spk[row["speaker"]].append(row["content"])
    if len(by_spk) == 1:
        return list(by_spk.keys())[0]
    scores = {}
    for spk, turns in by_spk.items():
        n       = len(turns)
        q       = sum(1 for t in turns if looks_like_question(t))
        avg_len = sum(len(t.split()) for t in turns) / max(n, 1)
        q_ratio = q / max(n, 1)
        scores[spk] = {
            "score":       (2.0 * q_ratio) + (1.0 / (1.0 + avg_len)),
            "q_ratio":     q_ratio,
            "avg_len":     avg_len,
            "total_words": sum(len(t.split()) for t in turns),
        }
    ranked = sorted(scores.items(), key=lambda kv: kv[1]["score"], reverse=True)
    top_spk, top_stats = ranked[0]
    _, second_stats    = ranked[1]
    if (top_stats["q_ratio"] >= 0.15
            and (top_stats["score"] - second_stats["score"]) >= 0.10):
        others = [s for s in by_spk if s != top_spk]
        if len(others) == 1:
            return others[0]
    fallback = {
        spk: (1.5 * s["total_words"] + 2.0 * s["avg_len"]
              - 10.0 * sum(1 for t in by_spk[spk] if looks_like_question(t)))
        for spk, s in scores.items()
    }
    return max(fallback, key=fallback.get)

