def normalize_turn(text):
    text = text.lower()
    text = re.sub(r"(\w+)'(\w+)", r"\1 \2", text)
    for pattern, replacement in CONTRACTIONS:
        text = re.sub(pattern, f" {replacement} ", text, flags=re.IGNORECASE)
    text = re.sub(r"[^\w\s]", " ", text)
    for filler in sorted(CUSTOM_FILLERS, key=len, reverse=True):
        text = re.sub(rf"\b{re.escape(filler)}\b", " ", text, flags=re.IGNORECASE)
    text = re.sub(r"\b\d{3,}\b", " ", text)
    text = re.sub(r"\s+", " ", text).strip()
    return text

def prepare_documents(transcripts_dict):
    docs     = []
    doc_rows = []
    all_rows = {}
    for filename, raw_text in transcripts_dict.items():
        rows = parse_transcript(raw_text)
        if not rows:
            continue
        all_rows[filename] = rows
        participant = detect_participant_speaker(rows)
        if participant is None:
            continue
        participant_turns = []
        for row in rows:
            if row["speaker"] == participant:
                cleaned = normalize_turn(row["content"])
                if len(cleaned.split()) >= MIN_TURN_WORDS:
                    participant_turns.append(cleaned)
        if len(participant_turns) < 2:
            continue
        n = len(participant_turns)
        for start in range(0, n, STRIDE):
            end   = start + WINDOW_SIZE
            chunk = " ".join(participant_turns[start:end]).strip()
            if len(chunk.split()) >= MIN_WINDOW_WORDS:
                docs.append(chunk)
                doc_rows.append({"filename": filename, "document": chunk})
            if end >= n:
                break
    return docs, pd.DataFrame(doc_rows), all_rows

