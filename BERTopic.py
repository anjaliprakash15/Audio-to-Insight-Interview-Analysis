def build_topic_model():
    custom_stop_words = list(
        ENGLISH_STOP_WORDS.union(CUSTOM_FILLERS).union(EXTRA_NOISE_WORDS)
    )
    vectorizer_model = CountVectorizer(
        stop_words=custom_stop_words,
        min_df=2,
        max_df=0.85,
        ngram_range=(1, 2),
        token_pattern=r"(?u)\b[a-zA-Z][a-zA-Z]{2,}\b",
    )
    umap_model = UMAP(
        n_neighbors=15, n_components=5,
        min_dist=0.1, metric="cosine", random_state=42,
    )
    hdbscan_model = HDBSCAN(
        min_cluster_size=8, min_samples=2,
        metric="euclidean", cluster_selection_method="eom",
        prediction_data=True,
    )
    representation_model = {
        "Main": KeyBERTInspired(),
        "MMR":  MaximalMarginalRelevance(diversity=0.5),
    }
    return BERTopic(
        vectorizer_model=vectorizer_model,
        umap_model=umap_model,
        hdbscan_model=hdbscan_model,
        representation_model=representation_model,
        top_n_words=10,
        calculate_probabilities=True,
        verbose=True,
    )

def compute_topic_scores(topic_model, topics):
    topic_info = topic_model.get_topic_info()
    total_docs  = sum(1 for t in topics if t != -1)
    rows = []
    for _, row in topic_info.iterrows():
        tid = row["Topic"]
        if tid == -1:
            continue
        kw_list   = topic_model.get_topic(tid) or []
        keywords  = [w for w, _ in kw_list]
        kw_scores = [s for _, s in kw_list]
        doc_count     = int(row["Count"])
        doc_pct       = round(doc_count / max(total_docs, 1) * 100, 1)
        keyword_score = round(sum(kw_scores) / max(len(kw_scores), 1), 4)
        composite     = round(
            0.4 * doc_pct + 0.4 * (keyword_score * 100) + 0.2 * min(doc_count / 5, 10), 2
        )
        rows.append({
            "topic_id":        tid,
            "topic_name":      name_topic(keywords),
            "doc_count":       doc_count,
            "doc_pct":         doc_pct,
            "composite_score": composite,
            "keyword_score":   keyword_score,
            "top_keywords":    ", ".join(keywords[:8]),
        })
    df = (pd.DataFrame(rows)
            .sort_values("composite_score", ascending=False)
            .reset_index(drop=True))
    df.insert(0, "rank", range(1, len(df) + 1))
    return df

def build_transcript_links(topic_model, docs_df, all_rows, scored_topics):
    topic_kws = {}
    for tid in scored_topics["topic_id"]:
        kw_list = topic_model.get_topic(tid) or []
        words   = set()
        for phrase, _ in kw_list:
            for w in phrase.lower().split():
                if len(w) > 3:
                    words.add(w)
        topic_kws[tid] = words
    link_rows = []
    for _, topic_row in scored_topics.iterrows():
        tid   = int(topic_row["topic_id"])
        tname = topic_row["topic_name"]
        kws   = topic_kws.get(tid, set())
        if not kws:
            continue
        files_in_topic = docs_df[docs_df["topic"] == tid]["filename"].unique()
        for fname in files_in_topic:
            rows = all_rows.get(fname, [])
            if not rows:
                continue
            matched = [
                row for row in rows
                if sum(1 for kw in kws if kw in row["content"].lower()) >= 1
            ]
            if not matched:
                continue
            matched.sort(key=lambda r: r["start"])
            link_rows.append({
                "topic_id":      tid,
                "topic_name":    tname,
                "filename":      fname,
                "start_time":    matched[0]["start"],
                "end_time":      matched[-1]["end"],
                "line_count":    len(matched),
                "matched_lines": "\n".join(r["raw_line"] for r in matched),
            })
    return pd.DataFrame(link_rows)

