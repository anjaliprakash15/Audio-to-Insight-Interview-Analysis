TMP_AUDIO_DIR = Path("/content/tmp_asr")
TMP_AUDIO_DIR.mkdir(parents=True, exist_ok=True)

def write_wav_slice(full_wav: Path, start_s: float, end_s: float, out_path: Path, sr=16000):
    y, _ = librosa.load(str(full_wav), sr=sr, mono=True, offset=max(0.0, start_s), duration=max(0.0, end_s-start_s))
    sf.write(str(out_path), y, sr)
    return out_path

def asr_transcribe_wav_paths(wav_paths, batch_size=8):
    # NeMo transcribe expects list of filepaths
    hypotheses_or_texts = asr_model.transcribe([str(p) for p in wav_paths], batch_size=batch_size)
    # extract the text from Hypothesis objects if they are returned
    texts = []
    for h_or_t in hypotheses_or_texts:
        if hasattr(h_or_t, 'text'):
            texts.append(h_or_t.text)
        else:
            texts.append(str(h_or_t)) # Fallback if it's already a string or something else
    return texts

def transcribe_segment_chunked(full_wav: Path, start_s: float, end_s: float,
                              max_chunk_s=25.0, overlap_s=2.0):
    """
    Transcribe [start_s, end_s] by chunking into smaller wav files.
    """
    duration = end_s - start_s
    if duration <= 0.05:
        return ""

    # If short enough, do one shot
    if duration <= max_chunk_s:
        tmp = TMP_AUDIO_DIR / f"{full_wav.stem}_{start_s:.2f}_{end_s:.2f}.wav".replace("..",".")
        write_wav_slice(full_wav, start_s, end_s, tmp)
        return asr_transcribe_wav_paths([tmp], batch_size=1)[0].strip()

    # Else chunk with overlap
    cur = start_s
    chunks = []
    chunk_paths = []
    while cur < end_s - 0.05:
        chunk_end = min(cur + max_chunk_s, end_s)
        tmp = TMP_AUDIO_DIR / f"{full_wav.stem}_{cur:.2f}_{chunk_end:.2f}.wav".replace("..",".")
        write_wav_slice(full_wav, cur, chunk_end, tmp)
        chunk_paths.append(tmp)
        chunks.append((cur, chunk_end))
        if chunk_end >= end_s:
            break
        cur = chunk_end - overlap_s  # overlap

    # Batch transcribe
    texts = []
    B = 8 if DEVICE == "cuda" else 2
    for i in range(0, len(chunk_paths), B):
        texts.extend(asr_transcribe_wav_paths(chunk_paths[i:i+B], batch_size=B))

    # Simple merge
    merged = " ".join([t.strip() for t in texts if t and t.strip()])
    return merged.strip()

def srt_timestamp(t: float) -> str:
    # SRT timestamp: HH:MM:SS,mmm
    if t < 0:
        t = 0.0
    ms = int(round((t - int(t)) * 1000))
    total = int(t)
    s = total % 60
    m = (total // 60) % 60
    h = (total // 3600)
    return f"{h:02d}:{m:02d}:{s:02d},{ms:03d}"

def write_srt(entries, out_path: Path):
    """
    entries: list of dict {start, end, speaker, text}
    """
    lines = []
    for i, e in enumerate(entries, 1):
        lines.append(str(i))
        lines.append(f"{srt_timestamp(e['start'])} --> {srt_timestamp(e['end'])}")
        # speaker label in SRT line
        spk = e["speaker"]
        txt = e["text"].strip()
        lines.append(f"{spk}: {txt}" if txt else f"{spk}:")
        lines.append("")  # blank line
    out_path.write_text("\n".join(lines), encoding="utf-8")

def build_outputs_for_file(full_wav: Path, session_out: Path, original_name: str = None):
    """
    Produces:
      - RTTM (copied standardized)
      - segments CSV
      - jsonl for BERTopic
      - readable txt
      - srt
    """
    session_out.mkdir(parents=True, exist_ok=True)

    # 1) diarization
    rttm_path = run_nemo_diarization(full_wav, session_out)

    # 2) parse + merge
    segs = merge_segments(parse_rttm(rttm_path), max_gap=0.35, min_dur=0.25)

    # 3) ASR each segment (chunked)
    rows = []
    srt_entries = []

    for (s, e, spk) in tqdm(segs, desc=f"ASR {full_wav.name}", leave=False):
        text = transcribe_segment_chunked(full_wav, s, e, max_chunk_s=25.0, overlap_s=2.0)

        row = {
            "file_id": full_wav.stem,
            "original_file": original_name or "",
            "speaker": spk,
            "start": round(s, 3),
            "end": round(e, 3),
            "duration": round(e - s, 3),
            "text": text
        }
        rows.append(row)

        srt_entries.append({
            "start": float(s),
            "end": float(e),
            "speaker": spk,
            "text": text
        })

    # 4) Save CSV + JSONL
    df = pd.DataFrame(rows)
    csv_path = session_out / f"{full_wav.stem}.segments.csv"
    jsonl_path = session_out / f"{full_wav.stem}.segments.jsonl"
    txt_path = session_out / f"{full_wav.stem}.transcript.txt"
    srt_path = session_out / f"{full_wav.stem}.srt"

    df.to_csv(csv_path, index=False, encoding="utf-8")
    with open(jsonl_path, "w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")

    # 5) Save readable transcript TXT
    # (speaker-tagged timeline)
    lines = []
    for r in rows:
        lines.append(f"[{r['start']:.2f}–{r['end']:.2f}] {r['speaker']}: {r['text']}".strip())
    txt_path.write_text("\n".join(lines), encoding="utf-8")

    # 6) Save SRT
    write_srt(srt_entries, srt_path)

    return {
        "rttm": str(rttm_path),
        "csv": str(csv_path),
        "jsonl": str(jsonl_path),
        "txt": str(txt_path),
        "srt": str(srt_path),
        "num_segments": len(rows)
    }

