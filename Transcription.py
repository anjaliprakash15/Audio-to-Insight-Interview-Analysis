def run_nemo_diarization(wav_path: Path, session_out: Path) -> Path:
    """
    Runs NeMo diarization inference on wav_path and writes RTTM into session_out.
    Returns RTTM path.
    """
    session_out.mkdir(parents=True, exist_ok=True)
    rttm_out = session_out / f"{wav_path.stem}.rttm"

    # Create a minimal diarization manifest
    manifest_path = session_out / f"{wav_path.stem}.diar_manifest.json"
    audio_len_sec = None

    # Use librosa to compute duration safely
    import librosa
    y, sr = librosa.load(str(wav_path), sr=16000, mono=True)
    audio_len_sec = float(len(y) / sr)

    diar_manifest_line = {
        "audio_filepath": str(wav_path),
        "offset": 0,
        "duration": audio_len_sec,
        "label": "infer",
        "text": "-",
        "num_speakers": None,  # let diarizer estimate
        "rttm_filepath": None,
        "uem_filepath": None
    }
    with open(manifest_path, "w", encoding="utf-8") as f:
        f.write(json.dumps(diar_manifest_line) + "\n")

    # Patch config
    local_cfg = OmegaConf.create(OmegaConf.to_container(cfg, resolve=True))
    local_cfg.diarizer.manifest_filepath = str(manifest_path)
    local_cfg.diarizer.out_dir = str(session_out)

    # Tenable msdd / neural refinement if config supports it
    # (If not available, NeMo will still produce RTTM from clustering diarization.)
    # These are common model names shipped via NGC:
    # - "titanet_large" for embeddings
    # - "diar_msdd_telephonic" for MS-DD refinement (if present in your NeMo build)
    try:
        local_cfg.diarizer.speaker_embeddings.model_path = "titanet_large"
    except Exception:
        pass

    # Attempt MS-DD refinement setup
    try:
        local_cfg.diarizer.msdd_model.model_path = "diar_msdd_telephonic"
        local_cfg.diarizer.msdd_model.parameters.use_embedding_features = True
    except Exception:
        pass

    # Run diarization
    try:
        from nemo.collections.asr.models import ClusteringDiarizer
        diarizer = ClusteringDiarizer(cfg=local_cfg)
        diarizer.diarize()

        # NeMo writes RTTM under out_dir/pred_rttms by default in many configs
        pred_dir = session_out / "pred_rttms"
        candidates = list(pred_dir.glob("*.rttm")) if pred_dir.exists() else []
        if not candidates:
            # Sometimes in "rttms" or directly in out_dir
            candidates = list(session_out.rglob("*.rttm"))

        # Pick the RTTM that matches this file
        picked = None
        for c in candidates:
            if wav_path.stem in c.name:
                picked = c
                break
        if picked is None and candidates:
            picked = candidates[0]

        if picked is None:
            raise FileNotFoundError("No RTTM produced by diarizer.")

        # Copy to standardized location/name
        shutil.copy2(picked, rttm_out)
        return rttm_out

    except Exception as e:
        raise RuntimeError(f"Diarization failed for {wav_path.name}: {e}")

import pandas as pd

def parse_rttm(rttm_path: Path):
    """
    RTTM format line example:
    SPEAKER file 1 start dur <NA> <NA> speaker_id <NA> <NA>
    """
    segments = []
    with open(rttm_path, "r", encoding="utf-8") as f:
        for line in f:
            if not line.strip():
                continue
            parts = line.strip().split()
            if len(parts) < 9:
                continue
            if parts[0] != "SPEAKER":
                continue
            start = float(parts[3])
            dur = float(parts[4])
            spk = parts[7]
            segments.append((start, start + dur, spk))

    segments.sort(key=lambda x: (x[0], x[2]))
    return segments

def merge_segments(segments, max_gap=0.35, min_dur=0.25):
    """
    Merge consecutive segments of same speaker if gap <= max_gap.
    Drop ultra-short segments (< min_dur).
    """
    if not segments:
        return []

    merged = []
    cur_s, cur_e, cur_spk = segments[0]

    for s, e, spk in segments[1:]:
        if spk == cur_spk and (s - cur_e) <= max_gap:
            cur_e = max(cur_e, e)
        else:
            if (cur_e - cur_s) >= min_dur:
                merged.append((cur_s, cur_e, cur_spk))
            cur_s, cur_e, cur_spk = s, e, spk

    if (cur_e - cur_s) >= min_dur:
        merged.append((cur_s, cur_e, cur_spk))

    return merged

